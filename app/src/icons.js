const PALETTE = {
  '#': ['ink', '#1B1916'],
  '+': ['accent', '#DE3B22'],
  '-': ['ink2', '#6A645B'],
  '*': ['accent-soft', '#F7D8CF'],
};

function gridFor(name) {
  if (!Object.prototype.hasOwnProperty.call(ICONS, name)) {
    throw new RangeError(`Unknown icon: ${name}`);
  }
  return ICONS[name].grid;
}

function runs(grid, draw) {
  grid.forEach((row, y) => {
    for (let x = 0; x < 16;) {
      const color = row[x];
      let end = x + 1;
      while (end < 16 && row[end] === color) end++;
      if (color !== '.') draw(x, y, end - x, color);
      x = end;
    }
  });
}

function escapeXML(value) {
  return String(value).replace(/[&<>"']/g, char => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;',
  })[char]);
}

// colors accepts either pixel keys ('#') or CSS names ('ink', '--ink').
// Default SVG fills inherit theme variables when used inline, with offline fallbacks.
export function iconSVG(name, { size = 48, colors } = {}) {
  const grid = gridFor(name);
  if (!Number.isFinite(size) || size <= 0) throw new RangeError('Invalid icon size');
  let body = '';
  runs(grid, (x, y, width, char) => {
    const [key, fallback] = PALETTE[char];
    const fill = colors?.[char] ?? colors?.[key] ?? colors?.[`--${key}`]
      ?? `var(--${key}, ${fallback})`;
    body += `<rect x="${x}" y="${y}" width="${width}" height="1" fill="${escapeXML(fill)}"/>`;
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 16 16" shape-rendering="crispEdges" role="img" aria-label="${escapeXML(name)}">${body}</svg>`;
}

// Integer scale keeps every source pixel aligned. Canvas stays transparent.
// Reads the root theme because canvas pixels cannot inherit CSS variables.
export function iconCanvas(name, scale = 6) {
  const grid = gridFor(name);
  if (!Number.isSafeInteger(scale) || scale < 1 || scale > 256) {
    throw new RangeError('Canvas scale must be an integer from 1 to 256');
  }
  const canvas = document.createElement('canvas');
  canvas.width = canvas.height = 16 * scale;
  canvas.style.imageRendering = 'pixelated';
  canvas.setAttribute('aria-label', name);
  const ctx = canvas.getContext('2d');
  if (!ctx) throw new Error('Canvas 2D unavailable');
  ctx.imageSmoothingEnabled = false;
  const theme = getComputedStyle(document.documentElement);
  const colors = Object.fromEntries(Object.entries(PALETTE).map(([char, [key, fallback]]) =>
    [char, theme.getPropertyValue(`--${key}`).trim() || fallback]));
  runs(grid, (x, y, width, char) => {
    ctx.fillStyle = colors[char];
    ctx.fillRect(x * scale, y * scale, width * scale, scale);
  });
  return canvas;
}
