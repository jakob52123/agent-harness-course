function stackedCars() {
  // Two solid 10×6 convertibles, separated by a completely empty row.
  // Four cells of rightward offset fit within the shared 14-cell safe area.
  const rows = [
    '..##.#....',
    '..##..#...',
    '.########.',
    '#########+',
    '##########',
    '.##....##.',
  ];
  return glyph([
    ...rows.map(row => '....' + row.replace(/[^.]/g, '-')),
    '..............',
    ...rows,
  ]);
}

