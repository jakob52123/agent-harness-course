// Orthographic pixel silhouettes. One cell is one stroke; no logos or assets.
// Patterns live in a shared 14×14 safe area inside the exported 16×16 grids.
function glyph(rows) {
  if (rows.length > 14 || rows.some(row => row.length > 14)) {
    throw new Error('Icon exceeds its safe area');
  }
  const blank = '.'.repeat(16);
  const top = Math.floor((16 - rows.length) / 2);
  return { grid: [
    ...Array(top).fill(blank),
    ...rows.map(row => `.${row.padEnd(14, '.')}.`),
    ...Array(16 - top - rows.length).fill(blank),
  ] };
}

